"""
=============================================================================
  MEDICAL RAG PIPELINE — Stage 4: Production Local Embedding Generator
=============================================================================
  Input  : chunks.json (generated by Stage 3 Semantic Chunk Builder)
  Output : embeddings.json (Vector embeddings + full metadata per chunk)

  Production Upgrades & Features
  ──────────────────────────────
  1. Strict Model Health Validation
     - Verifies Ollama server reachable on http://localhost:11434.
     - Verifies required model ('nomic-embed-text') is loaded.
     - Immediately aborts pipeline with clear error message if model is missing.

  2. Robust Retry Mechanism with Exponential Backoff
     - Up to 3 retries on HTTP errors, timeouts, or connection failures.
     - Delays: 1s, 2s, 4s before marking chunk as failed.

  3. Dynamic Vector Dimension Validation
     - Determines vector dimension dynamically from first valid embedding (768).
     - Validates all subsequent embeddings against this expected dimension.

  4. Generic Metadata Preservation & SHA-256 Content Hashing
     - Computes sha256 content hash for chunk modification tracking.
     - Automatically preserves all chunk metadata without fragile key lists.

  5. Strict Resume Validation & Self-Healing
     - Validates existing embeddings.json on startup.
     - Automatically discards outdated, corrupted, or dimension-mismatched
       records and re-embeds them automatically.

  6. Advanced Validation Engine & Performance Metrics
     - Checks duplicate IDs, duplicate vectors, empty content/vectors,
       invalid page ranges, invalid token counts, NaN/Inf corruption.
     - Reports throughput (chunks/sec), batch counts, latency, and totals.
=============================================================================
"""

