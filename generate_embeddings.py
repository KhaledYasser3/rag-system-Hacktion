@dataclass
class PipelineConfig:
    """Centralized configuration settings for the Embedding Pipeline."""
    model_name: str = "nomic-embed-text"
    ollama_host: str = "http://localhost:11434"
    input_path: str = "chunks.json"
    output_path: str = "embeddings.json"
    batch_size: int = 32
    timeout_seconds: int = 30
    max_retries: int = 3
    retry_delays: Tuple[int, ...] = (1, 2, 4)
    log_level: str = "INFO"


# Initialize Logger
config = PipelineConfig()
logging.basicConfig(
    level=getattr(logging, config.log_level),
    format="%(asctime)s [%(levelname)s] %(message)s",
    handlers=[logging.StreamHandler(sys.stdout)]
)
logger = logging.getLogger("EmbeddingGenerator")


def _safe_print(*args, **kwargs) -> None:
    """Drop-in replacement for print() that never crashes on console encoding errors."""
    try:
        print(*args, **kwargs)
    except UnicodeEncodeError:
        sep = kwargs.get("sep", " ")
        end = kwargs.get("end", "\n")
        file = kwargs.get("file", sys.stdout)
        msg = sep.join(str(a) for a in args) + end
        msg = msg.replace("✅", "[OK]").replace("⚠️", "[WARN]").replace("❌", "[FAIL]").replace("✓", "[PASS]")
        enc = getattr(file, "encoding", "ascii") or "ascii"
        try:
            file.buffer.write(msg.encode(enc, errors="replace"))
        except Exception:
            pass


